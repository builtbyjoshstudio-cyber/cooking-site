/* =========================================================
   SERVICE WORKER — offline support for cooking.builtbyjoshstudio.com
   Generated by .github/build_sw.py from the pages that exist. Do not edit by hand:
   run  python3 .github/build_sw.py  (the pre-commit hook refuses a stale copy).

   HOW A RETURNING VISITOR GETS UPDATES
   · HTML pages: network-first. Online, every page request goes to the server
     and revalidates (cache: 'no-cache'), so a normal reload, or a click, shows
     the page as deployed. The saved copy is only the offline fallback.
   · Same-origin CSS and JS: every page asks for them at a versioned address
     (styles.css?v=<hash of the file>, written at build time), so a changed file
     has a new address that no cache holds: not the browser's 10-minute HTTP
     cache (GitHub Pages: max-age=600), not the copy Chrome keeps in memory and
     reuses on a normal reload (that reuse never reaches this worker), not the
     caches below. They are fetched network-first with 'no-cache' as well.
   · Fonts and images: from the cache, refreshed in the background
     (stale-while-revalidate). Every font is precached.
   · Anything else (analytics, other sites) is left to the browser.

   HOW OLD CACHES ARE CLEARED
   CACHE_VERSION is a hash of this worker and of every file it precaches, so a
   deploy that changes any of them changes this file. The browser checks for a
   new worker on page loads (kinetic.js asks on every load). The new worker:
     1. precaches fresh copies (cache: 'reload', nothing from the browser's cache);
     2. on activation, saves again the pages this visitor had opened (from the
        older caches and the open tabs, the first page visited included), so
        they still open offline;
     3. deletes every older jjk- cache, then takes over the open tabs.
   ========================================================= */
